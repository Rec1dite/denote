// Resolves the latest GitHub release at build time (falling back to the package version) so the
// install section can link to and download the newest .vsix. The site also refreshes this at
// runtime, so it stays current without a rebuild.
import { existsSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { writeIfChanged } from "./write.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const REPO = "rec1dite/denote";
const target = resolve(here, "../src/release.js");

const pkg = JSON.parse(readFileSync(resolve(here, "../../package.json"), "utf8"));
const fallback = {
  tag: `v${pkg.version}`,
  version: pkg.version,
  vsixUrl: `https://github.com/${REPO}/releases/download/v${pkg.version}/denote-${pkg.version}.vsix`,
  releaseUrl: `https://github.com/${REPO}/releases/latest`,
};

if (process.env.ROLLUP_WATCH && existsSync(target)) {
  // In watch mode reuse the value resolved on the first build; the site refreshes it in the browser.
  console.log("release: using existing (watch)");
} else {
  let release = fallback;
  try {
    const response = await fetch(`https://api.github.com/repos/${REPO}/releases/latest`, {
      headers: { "User-Agent": "denote-docs", Accept: "application/vnd.github+json" },
      signal: AbortSignal.timeout(8000),
    });
    if (response.ok) {
      const data = await response.json();
      const tag = data.tag_name ?? fallback.tag;
      const version = tag.replace(/^v/, "");
      const asset = (data.assets ?? []).find((a) => a.name?.endsWith(".vsix"));
      release = {
        tag,
        version,
        vsixUrl:
          asset?.browser_download_url ??
          `https://github.com/${REPO}/releases/download/${tag}/denote-${version}.vsix`,
        releaseUrl: data.html_url ?? fallback.releaseUrl,
      };
    } else {
      console.log(`latest release fetch: HTTP ${response.status}, using fallback v${pkg.version}`);
    }
  } catch (err) {
    console.log(`latest release fetch failed (${err.message}), using fallback v${pkg.version}`);
  }
  const changed = writeIfChanged(
    target,
    `// Generated by scripts/release.mjs — do not edit.\nexport default ${JSON.stringify(release)};\n`,
  );
  console.log(`release: ${release.tag}${changed ? "" : " (unchanged)"}`);
}
