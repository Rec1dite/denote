// Inlines the real VSCode codicon SVGs (docs/icons/*.svg) into src/icons.js so they can be
// rendered inline (and inherit `currentColor`) without client-side fetches.
import { readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { writeIfChanged } from "./write.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const iconsDir = resolve(here, "../icons");

const icons = {};
for (const file of readdirSync(iconsDir)) {
  if (!file.endsWith(".svg")) continue;
  icons[file.slice(0, -4)] = readFileSync(join(iconsDir, file), "utf8").trim();
}

const target = resolve(here, "../src/icons.js");
const changed = writeIfChanged(target, `// Generated by scripts/icons.mjs — do not edit.\nexport default ${JSON.stringify(icons)};\n`);
console.log(`icons: ${Object.keys(icons).length}${changed ? "" : " (unchanged)"}`);

