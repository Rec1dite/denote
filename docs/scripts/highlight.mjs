// Build-time syntax highlighting with the Catppuccin Mocha theme (Shiki).
// Emits src/highlighted.js as per-line HTML so the site ships pre-highlighted, no client JS,
// and the interactive demo can inject CodeLens rows above cell markers.
import { mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { createHighlighter } from "shiki";
import * as snippets from "../src/snippets.js";
import { writeIfChanged } from "./write.mjs";

const here = dirname(fileURLToPath(import.meta.url));

const LANG_BY_KEY = { install: "bash", settings: "json" };

function escapeHtml(value) {
  return value.replace(/[&<>]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" })[c]);
}

const highlighter = await createHighlighter({
  themes: ["catppuccin-mocha"],
  langs: ["typescript", "javascript", "json", "bash"],
});

const highlighted = {};
for (const [key, code] of Object.entries(snippets)) {
  const lang = LANG_BY_KEY[key] ?? "typescript";
  const lines = [];
  try {
    const { tokens } = highlighter.codeToTokens(code, { lang, theme: "catppuccin-mocha" });
    for (const lineTokens of tokens) {
      lines.push({
        html: lineTokens.map((t) => `<span style="color:${t.color}">${escapeHtml(t.content)}</span>`).join(""),
        text: lineTokens.map((t) => t.content).join(""),
      });
    }
  } catch (err) {
    console.error(`highlight failed for ${key}:`, err.message);
    for (const line of code.split("\n")) lines.push({ html: escapeHtml(line), text: line });
  }
  highlighted[key] = { lines };
}

const target = resolve(here, "../src/highlighted.js");
mkdirSync(dirname(target), { recursive: true });
const changed = writeIfChanged(
  target,
  `// Generated by scripts/highlight.mjs — do not edit.\nexport default ${JSON.stringify(highlighted)};\n`,
);
console.log(`highlighted ${Object.keys(highlighted).length} snippets${changed ? "" : " (unchanged)"}`);
